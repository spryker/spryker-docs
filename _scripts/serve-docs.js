#!/usr/bin/env node
// Serves the docs locally in Docker and builds only the docs sections you pass.
//
// Usage:
//   npm run docs:serve              # full site
//   npm run docs:serve -- pbc       # only docs/pbc
//   npm run docs:serve -- pbc dg    # several sections
//
// Pages in excluded sections are not built, so links into them are broken locally.

const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');

const root = path.resolve(__dirname, '..');
const devConfigPath = path.join(root, '_config_dev.yml');
const siteDir = path.join(root, '_site');

const sections = fs
  .readdirSync(path.join(root, 'docs'), { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name);

const keep = process.argv.slice(2);
const unknown = keep.filter((section) => !sections.includes(section));
if (unknown.length) {
  console.error(`Unknown section(s): ${unknown.join(', ')}. Available: ${sections.join(', ')}`);
  process.exit(1);
}

const skipped = keep.length ? sections.filter((section) => !keep.includes(section)) : [];

// Jekyll replaces the `exclude` list instead of merging it, so copy the base list from _config.yml.
const baseConfig = fs.readFileSync(path.join(root, '_config.yml'), 'utf8');
const excludeBlock = baseConfig.match(/^exclude:\n((?:[ \t]+- .*\n)+)/m);
if (!excludeBlock) {
  console.error('Could not find the `exclude` list in _config.yml.');
  process.exit(1);
}
const baseExclude = excludeBlock[1]
  .trim()
  .split('\n')
  .map((line) => line.replace(/^\s*- /, '').trim());

const exclude = [...baseExclude, ...skipped.map((section) => `docs/${section}/`)];
const devConfig =
  '# Generated by _scripts/serve-docs.js. Do not edit or commit.\n' +
  `exclude:\n${exclude.map((entry) => `  - ${entry}`).join('\n')}\n`;

// Stale pages from a previous section selection stay in _site, so clear it when the selection changes.
const previousConfig = fs.existsSync(devConfigPath) ? fs.readFileSync(devConfigPath, 'utf8') : null;
if (previousConfig !== devConfig) {
  fs.rmSync(siteDir, { recursive: true, force: true });
  fs.rmSync(path.join(root, '.jekyll-metadata'), { force: true });
}
fs.writeFileSync(devConfigPath, devConfig);

console.log(keep.length ? `Building sections: ${keep.join(', ')}` : 'Building the full site');

const result = spawnSync(
  'docker',
  [
    'compose', 'run', '--rm', '--service-ports', 'jekyll',
    'bundle', 'exec', 'jekyll', 'serve',
    '--host', '0.0.0.0',
    '--livereload',
    '--incremental',
    '--config', '_config.yml,_config_dev.yml',
  ],
  { cwd: root, stdio: 'inherit' }
);

process.exit(result.status ?? 1);
